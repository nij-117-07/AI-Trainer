class Humanizer(dspy.Signature):
    """
    You are a Text Humanizer. Your job is to rewrite AI-sounding text so it reads
    like it was written by a real person.

    Rules:
    - Vary sentence length — mix short punchy sentences with longer ones.
    - Add natural imperfections: occasional contractions, colloquial phrases,
      mild informality where appropriate.
    - Remove robotic transitions ("Furthermore", "Moreover", "In conclusion").
    - Add personality: opinions, anecdotes, rhetorical questions, or emotion.
    - Use specific examples instead of generic statements.
    - Break up uniform paragraph structures.
    - Keep the original meaning and key information intact.
    - Match the tone specified by the user (casual, professional, academic, etc.).
    """

    # ── Inputs ──
    ai_text: str = dspy.InputField(
        description="The AI-sounding text that needs to be humanized."
    )
    target_tone: str = dspy.InputField(
        description="Desired tone for the output (e.g., casual, professional, "
                    "conversational, academic, witty)."
    )
    detection_feedback: Optional[str] = dspy.InputField(
        default=None,
        description="Optional feedback from the AI Detector — flagged patterns and "
                    "suggested changes to specifically address."
    )

    # ── Outputs ──
    humanized_text: str = dspy.OutputField(
        description="The rewritten text that sounds natural and human-written."
    )
    changes_made: List[str] = dspy.OutputField(
        description="List of specific changes made and why they help the text "
                    "sound more human."
    )
    confidence: float = dspy.OutputField(
        description="Your confidence (0.0 to 1.0) that this rewritten text would "
                    "pass as human-written."
    )


# ─── Execution Function ───
def humanize_text(model_name, api_key, api_base, text, tone="conversational", feedback=None):
    """
    Rewrites AI-sounding text to feel more human.
    """
    with dspy.context(lm=dspy.LM(
        model=f'openai/{model_name}',
        api_key=api_key,
        api_base=api_base,
        temperature=0.7,   # Higher temp for more natural, creative output
        stop=None,
        cache=False
    )):
        humanizer = dspy.Predict(Humanizer)

        response = humanizer(
            ai_text=text,
            target_tone=tone,
            detection_feedback=feedback or "No specific feedback provided."
        )

        return response