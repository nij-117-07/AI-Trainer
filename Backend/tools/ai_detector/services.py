import logging
from typing import List, Literal, Optional

import dspy

from core.dspy_utils import build_lm, run_predictor
from tools.ai_detector.schemas import (
    AIDetectionRequest,
    AIDetectionResponse,
    HumanizerRequest,
    HumanizerResponse,
)

logger = logging.getLogger(__name__)

DEFAULT_DETECTION_CONTEXT = "No additional context provided."
DEFAULT_DETECTION_FEEDBACK = "No specific feedback provided."
DEFAULT_ADDITIONAL_COMMENTS = "No additional comments provided."


class AIDetectorError(Exception):
    """Base exception for all AI detector module failures."""


class DetectionError(AIDetectorError):
    """Raised when the AI detection pipeline fails to produce a result."""


class HumanizationError(AIDetectorError):
    """Raised when the humanizer pipeline fails to produce content."""


class AIDetectorSignature(dspy.Signature):
    """
    You are an expert AI-Text Detector. Your job is to analyze the given text
    and determine how likely it was generated by an AI (like ChatGPT, Gemini, etc.).

    You must:
    1. Assign an AI probability score between 0.0 (fully human) and 1.0 (fully AI).
    2. Provide a clear verdict: "Likely AI", "Likely Human", or "Mixed".
    3. Explain your reasoning — cite specific phrases, structures, or patterns.
    4. List the exact patterns you flagged (e.g., repetitive transitions, overly
       formal tone, lack of personal anecdotes, uniform sentence length).
    5. Suggest concrete, actionable changes to make the text sound more human.

    Consider these AI tells:
    - Overuse of transitions like "Furthermore", "Moreover", "In conclusion"
    - Uniform sentence length and structure
    - Lack of personal experience, emotion, or imperfection
    - Overly polished grammar with no colloquialisms
    - Generic, non-specific examples
    - Repetitive paragraph structures
    - Excessive hedging or balanced "on the other hand" phrasing
    """

    text_to_check: str = dspy.InputField(
        description="The text to analyze for AI-generated content."
    )
    additional_comments: Optional[str] = dspy.InputField(
        default=None,
        description=(
            "Optional extra context from the user — e.g., where the text came "
            "from, what tool might have written it, or specific concerns."
        ),
    )

    ai_score: float = dspy.OutputField(
        description="AI probability score from 0.0 (fully human) to 1.0 (fully AI)."
    )
    verdict: Literal["Likely AI", "Likely Human", "Mixed"] = dspy.OutputField(
        description="Final verdict on whether the text is AI-generated."
    )
    reason: str = dspy.OutputField(
        description=(
            "Detailed explanation of why this score was given, citing specific "
            "phrases, structures, or patterns found in the text."
        )
    )
    flagged_patterns: List[str] = dspy.OutputField(
        description="List of specific AI-telltale patterns detected in the text."
    )
    suggested_changes: List[str] = dspy.OutputField(
        description=(
            "Actionable suggestions to rewrite the text so it sounds more human. "
            "Be specific — reference actual parts of the text."
        )
    )


class HumanizerSignature(dspy.Signature):
    """
    You are a Text Humanizer. Your job is to rewrite AI-sounding text so it reads
    like it was written by a real person.

    Rules:
    - Vary sentence length — mix short punchy sentences with longer ones.
    - Add natural imperfections: occasional contractions, colloquial phrases,
      mild informality where appropriate.
    - Remove robotic transitions ("Furthermore", "Moreover", "In conclusion").
    - Add personality: opinions, anecdotes, rhetorical questions, or emotion.
    - Use specific examples instead of generic statements.
    - Break up uniform paragraph structures.
    - Keep the original meaning and key information intact.
    - Match the tone specified by the user (casual, professional, academic, etc.).
    - Honor any additional comments or constraints supplied by the user.
    """

    ai_text: str = dspy.InputField(
        description="The AI-sounding text that needs to be humanized."
    )
    target_tone: str = dspy.InputField(
        description=(
            "Desired tone for the output (e.g., casual, professional, "
            "conversational, academic, witty)."
        )
    )
    detection_feedback: Optional[str] = dspy.InputField(
        default=None,
        description=(
            "Optional feedback from the AI Detector — flagged patterns and "
            "suggested changes to specifically address."
        ),
    )
    additional_comments: Optional[str] = dspy.InputField(
        default=None,
        description=(
            "Optional extra instructions from the user — e.g., preserve certain "
            "phrasing, target audience, or contextual constraints."
        ),
    )

    humanized_text: str = dspy.OutputField(
        description="The rewritten text that sounds natural and human-written."
    )
    changes_made: List[str] = dspy.OutputField(
        description=(
            "List of specific changes made and why they help the text "
            "sound more human."
        )
    )
    confidence: float = dspy.OutputField(
        description=(
            "Your confidence (0.0 to 1.0) that this rewritten text would "
            "pass as human-written."
        )
    )


class AIDetectorService:
    """Stateless business layer wrapping the DSPy detection and humanizer pipelines."""

    def __init__(self) -> None:
        self.detection_lm = build_lm(temperature=0.2, cache=False)
        self.humanizer_lm = build_lm(temperature=0.7, cache=False)

    def detect(self, data: AIDetectionRequest) -> AIDetectionResponse:
        """
        Runs the AI detector over the supplied text.

        Args:
            data (AIDetectionRequest): The validated detection request.

        Returns:
            AIDetectionResponse: The AI score, verdict, reason, flagged
            patterns, and suggested changes.

        Raises:
            DetectionError: If the detection pipeline fails.
        """
        try:
            result = run_predictor(
                AIDetectorSignature,
                self.detection_lm,
                text_to_check=data.text_to_check,
                additional_comments=data.additional_comments or DEFAULT_DETECTION_CONTEXT,
            )
            response = AIDetectionResponse(
                ai_score=float(result.ai_score),
                verdict=result.verdict,
                reason=str(result.reason),
                flagged_patterns=[str(p) for p in result.flagged_patterns],
                suggested_changes=[str(s) for s in result.suggested_changes],
            )
            logger.info(
                "AI detection completed with score=%.3f verdict='%s'",
                response.ai_score,
                response.verdict,
            )
            return response
        except Exception as exc:
            logger.error("AI detection failed: %s", exc, exc_info=True)
            raise DetectionError(str(exc)) from exc

    def humanize(self, data: HumanizerRequest) -> HumanizerResponse:
        """
        Rewrites AI-sounding text so it reads like human-written content.

        Args:
            data (HumanizerRequest): The validated humanizer request, including
                the optional additional comments supplied by the user.

        Returns:
            HumanizerResponse: The humanized text, the changes made, and the
            confidence score.

        Raises:
            HumanizationError: If the humanizer pipeline fails.
        """
        try:
            result = run_predictor(
                HumanizerSignature,
                self.humanizer_lm,
                ai_text=data.ai_text,
                target_tone=data.target_tone,
                detection_feedback=data.detection_feedback or DEFAULT_DETECTION_FEEDBACK,
                additional_comments=data.additional_comments or DEFAULT_ADDITIONAL_COMMENTS,
            )
            response = HumanizerResponse(
                humanized_text=str(result.humanized_text),
                changes_made=[str(c) for c in result.changes_made],
                confidence=float(result.confidence),
            )
            logger.info(
                "Humanization completed with confidence=%.3f tone='%s'",
                response.confidence,
                data.target_tone,
            )
            return response
        except Exception as exc:
            logger.error("Humanization failed: %s", exc, exc_info=True)
            raise HumanizationError(str(exc)) from exc
